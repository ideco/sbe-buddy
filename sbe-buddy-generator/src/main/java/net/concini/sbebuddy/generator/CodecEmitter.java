package net.concini.sbebuddy.generator;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.io.Writer;
import java.nio.ByteOrder;
import java.util.ArrayList;
import java.util.List;

import org.agrona.generation.DynamicPackageOutputManager;
import org.jspecify.annotations.Nullable;

import uk.co.real_logic.sbe.generation.java.JavaUtil;
import uk.co.real_logic.sbe.ir.Encoding;
import uk.co.real_logic.sbe.ir.GenerationUtil;
import uk.co.real_logic.sbe.ir.Ir;
import uk.co.real_logic.sbe.ir.Token;

/**
 * Step 7 of the pipeline: one {@code <Msg>Codec} per message, from the IR the
 * way {@code JavaGenerator} reads it and from {@link Annotated} for the Java
 * face, written from text-block templates. Every flyweight member it calls is
 * named through {@link JavaUtil}, so it calls what was generated. A construct
 * the codec does not cover yet is a problem naming the message; nothing is
 * skipped silently.
 */
public final class CodecEmitter {

	private static final String STANDARD_HEADER = "messageHeader";

	private static final Template CODEC = Template.of(
			"""
					package {package};

					/** Generated by sbe-buddy from the schema of this package; do not edit. */
					@javax.annotation.processing.Generated("net.concini.sbebuddy")
					public final class {codec} implements net.concini.sbebuddy.Codec<{record}> {

						private final {flyweights}.{header}Encoder headerEncoder = new {flyweights}.{header}Encoder();
						private final {flyweights}.{header}Decoder headerDecoder = new {flyweights}.{header}Decoder();
						private final {flyweights}.{message}Encoder encoder = new {flyweights}.{message}Encoder();
						private final {flyweights}.{message}Decoder decoder = new {flyweights}.{message}Decoder();
						private int lastDecodedLength;

						public {codec}() {
						}

						@Override
						public int encodedLength({record} value) {
							return {flyweights}.{header}Encoder.ENCODED_LENGTH + {flyweights}.{message}Encoder.BLOCK_LENGTH;
						}

						@Override
						public int encode({record} value, org.agrona.MutableDirectBuffer buffer, int offset) {
							encoder.wrapAndApplyHeader(buffer, offset, headerEncoder);
							{encodeFields}
							return {flyweights}.{header}Encoder.ENCODED_LENGTH + encoder.encodedLength();
						}

						@Override
						public {record} decode(org.agrona.DirectBuffer buffer, int offset) {
							headerDecoder.wrap(buffer, offset);
							if (headerDecoder.schemaId() != {flyweights}.{message}Decoder.SCHEMA_ID
									|| headerDecoder.templateId() != {flyweights}.{message}Decoder.TEMPLATE_ID) {
								throw new IllegalArgumentException(
										"not a {message}: schemaId " + headerDecoder.schemaId() + ", templateId " + headerDecoder.templateId());
							}
							decoder.wrap(buffer, offset + {flyweights}.{header}Decoder.ENCODED_LENGTH, headerDecoder.blockLength(), headerDecoder.version());
							{record} value = new {record}(
									{decodeFields}
							);
							lastDecodedLength = {flyweights}.{header}Decoder.ENCODED_LENGTH + decoder.encodedLength();
							return value;
						}

						@Override
						public int lastDecodedLength() {
							return lastDecodedLength;
						}

						@Override
						public int decodedLength(org.agrona.DirectBuffer buffer, int offset) {
							headerDecoder.wrap(buffer, offset);
							return {flyweights}.{header}Decoder.ENCODED_LENGTH + headerDecoder.blockLength();
						}
					}
					"""
	);

	private static final Template ENCODE_FIELD = Template.of("encoder.{property}(value.{component}());");

	private static final Template DECODE_FIELD = Template.of("decoder.{property}()");

	private final Ir ir;
	private final Annotated annotated;
	private final List<Problem> problems = new ArrayList<>();

	private CodecEmitter(Ir ir, Annotated annotated) {
		this.ir = ir;
		this.annotated = annotated;
	}

	/**
	 * Writes each message's codec through the output, which must already name the
	 * schema package; an output that fails to write is an
	 * {@link UncheckedIOException}.
	 */
	public static List<Problem> emit(Ir ir, Annotated annotated, DynamicPackageOutputManager output) {
		CodecEmitter emitter = new CodecEmitter(ir, annotated);
		for (Annotated.Message message : annotated.messages()) {
			String source = emitter.codec(message);
			if (source != null) {
				try (Writer writer = output.createOutput(message.javaName() + "Codec")) {
					writer.write(source);
				} catch (IOException e) {
					throw new UncheckedIOException(e);
				}
			}
		}
		return List.copyOf(emitter.problems);
	}

	/**
	 * The codec's source, or null with a problem for a construct not covered yet.
	 */
	private @Nullable String codec(Annotated.Message message) {
		String header = ir.headerStructure().tokens().get(0).name();
		if (!header.equals(STANDARD_HEADER)) {
			return refuse(message, "a header type of its own");
		}
		if (ir.byteOrder() != ByteOrder.LITTLE_ENDIAN) {
			return refuse(message, "big-endian byte order");
		}
		List<Token> tokens = ir.getMessage(message.id());
		List<Token> fields = new ArrayList<>();
		List<Token> groups = new ArrayList<>();
		List<Token> varData = new ArrayList<>();
		int index = GenerationUtil.collectFields(tokens, 1, fields);
		index = GenerationUtil.collectGroups(tokens, index, groups);
		GenerationUtil.collectVarData(tokens, index, varData);
		if (!groups.isEmpty()) {
			return refuse(message, "a group");
		}
		if (!varData.isEmpty()) {
			return refuse(message, "var-data");
		}
		List<String> encodeFields = new ArrayList<>();
		List<String> decodeFields = new ArrayList<>();
		for (int i = 0; i < fields.size(); i += fields.get(i).componentTokenCount()) {
			Token field = fields.get(i);
			String unsupported = unsupported(field, fields.get(i + 1));
			if (unsupported != null) {
				return refuse(message, unsupported);
			}
			String property = JavaUtil.formatPropertyName(field.name());
			encodeFields
					.add(ENCODE_FIELD.fill("property", property, "component", component(message, field).javaName()));
			decodeFields.add(DECODE_FIELD.fill("property", property));
		}
		String record = annotated.packageName() + "." + message.javaName();
		return CODEC.fill(
				"package", annotated.packageName(),
				"codec", message.javaName() + "Codec",
				"record", record,
				"flyweights", ir.applicableNamespace(),
				"header", JavaUtil.formatClassName(header),
				"message", JavaUtil.formatClassName(tokens.get(0).name()),
				"encodeFields", String.join("\n", encodeFields),
				"decodeFields", String.join(",\n", decodeFields)
		);
	}

	/**
	 * What the codec cannot do with the field yet, or null for a plain primitive.
	 */
	private static @Nullable String unsupported(Token field, Token type) {
		if (field.version() > 0) {
			return "a field added in a later version";
		}
		return switch (type.signal()) {
			case BEGIN_ENUM -> "an enum";
			case BEGIN_SET -> "a set";
			case BEGIN_COMPOSITE -> "a composite";
			case ENCODING -> encodingUnsupported(type);
			default -> throw new IllegalStateException("a field of " + type.signal());
		};
	}

	private static @Nullable String encodingUnsupported(Token type) {
		if (type.arrayLength() > 1) {
			return "an array";
		}
		if (type.encoding().presence() == Encoding.Presence.CONSTANT) {
			return "a constant";
		}
		if (type.encoding().presence() == Encoding.Presence.OPTIONAL) {
			return "an optional field";
		}
		return null;
	}

	private @Nullable String refuse(Annotated.Message message, String construct) {
		problems.add(new Problem(message, "no codec for " + construct + " yet; set codecs = false on @SbeSchema"));
		return null;
	}

	/** The record component the field token came from, by wire name. */
	private static Annotated.Field component(Annotated.Message message, Token field) {
		for (Annotated.Component component : message.components()) {
			if (component instanceof Annotated.Field candidate && wireName(candidate).equals(field.name())) {
				return candidate;
			}
		}
		throw new IllegalStateException(message.javaName() + " has no component for field " + field.name());
	}

	private static String wireName(Annotated.Field field) {
		return field.name().isEmpty() ? field.javaName() : field.name();
	}
}
